/**
 * The Postgres schema is derived, never written by hand: a fresh in-memory SQLite is migrated to a version and its schema is
 * translated (tables, indexes, triggers). Goal: the two engines can never drift apart, and the 29 SQLite-era migrations are not
 * rewritten. Check: `pg.test.ts` compares every table's columns and primary key on both engines.
 *
 * Every Postgres table also gets a hidden `rowid` (an identity column): SQLite has one implicitly and a few queries order by it
 * as a tie-break («the order it was written in»). The adapter never returns it as part of a row.
 */
import { SqliteDatabase } from './sqlite.ts';
import { translateDdl, translateTrigger } from './translate.ts';

const memo = new Map<number, string[]>();

export function postgresSchemaAt(version: number, migrate: (db: SqliteDatabase, target: number) => unknown): string[] {
  if (!memo.has(version)) memo.set(version, derive(version, migrate));
  return memo.get(version)!;
}

function derive(version: number, migrate: (db: SqliteDatabase, target: number) => unknown): string[] {
  const lite = SqliteDatabase.open(':memory:');
  try {
    migrate(lite, version);
    const items = lite.raw.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid").all() as Array<{ type: string; name: string; tbl_name: string; sql: string }>;
    const out: string[] = [];
    for (const it of items) {
      if (it.type === 'table') {
        out.push(translateDdl(it.sql));
        if (it.name !== 'schema_migrations') out.push(`ALTER TABLE "${it.name}" ADD COLUMN rowid BIGINT GENERATED BY DEFAULT AS IDENTITY`);
      } else if (it.type === 'index') out.push(translateDdl(it.sql));
      else if (it.type === 'trigger') out.push(translateTrigger(it.sql));
      else throw new Error(`schema item not translated: ${it.type} ${it.name}`);
    }
    return out;
  } finally { lite.close(); }
}
